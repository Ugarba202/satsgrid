/**
 * Utility functions for Lightning backend and network identification.
 *
 * Implements authoritative node metadata resolution with safe fallback
 * to invoice inspection when node metadata is loading or unavailable.
 */

import { NodeLightningInfo } from "./node";

export type LightningBackendIdentity =
  | "mock"
  | "lnd_rest"
  | "nwc"
  | "unknown";

export type LightningNetworkIdentity =
  | "mock"
  | "regtest"
  | "testnet"
  | "mainnet"
  | "signet"
  | "unknown";

export interface AuthoritativeNetworkInfo {
  isAuthoritative: boolean;
  backend: LightningBackendIdentity;
  network: LightningNetworkIdentity;
  displayName: string;
}

/**
 * Format a human-readable display label given authoritative backend & network identities.
 */
export function formatNetworkDisplay(
  backend: string | undefined | null,
  network: string | undefined | null
): string {
  const normBackend = (backend || "").trim().toLowerCase();
  const normNetwork = (network || "").trim().toLowerCase();

  if (normBackend === "mock") {
    const netSuffix = normNetwork ? ` (${normNetwork})` : "";
    return `Mock Lightning${netSuffix}`;
  }

  const backendLabel =
    normBackend === "lnd_rest" || normBackend === "lnd"
      ? "LND"
      : normBackend === "nwc"
      ? "NWC"
      : "";

  let networkLabel = "Lightning Network";
  if (normNetwork === "mainnet") {
    networkLabel = "Bitcoin Mainnet";
  } else if (normNetwork === "testnet") {
    networkLabel = "Bitcoin Testnet";
  } else if (normNetwork === "regtest") {
    networkLabel = "Bitcoin Regtest (Polar)";
  } else if (normNetwork === "signet") {
    networkLabel = "Bitcoin Signet";
  }

  if (backendLabel && networkLabel !== "Lightning Network") {
    return `${networkLabel} [${backendLabel}]`;
  }

  return networkLabel;
}

/**
 * Resolve authoritative network identity from node health metadata if available,
 * with optional fallback to invoice-based inspection when the node response is
 * unavailable, loading, or missing.
 */
export function resolveNetworkIdentity(
  nodeLightning?: NodeLightningInfo | null,
  fallbackInvoice?: string | null
): AuthoritativeNetworkInfo {
  if (nodeLightning && nodeLightning.backend && nodeLightning.network) {
    const backend = nodeLightning.backend.toLowerCase() as LightningBackendIdentity;
    const network = nodeLightning.network.toLowerCase() as LightningNetworkIdentity;
    return {
      isAuthoritative: true,
      backend,
      network,
      displayName: formatNetworkDisplay(backend, network),
    };
  }

  // Fallback to invoice-based inspection if node metadata is not yet loaded
  const fallback = getInvoiceNetworkInfo(fallbackInvoice);
  return {
    isAuthoritative: false,
    backend: fallback.network === "mock" ? "mock" : "unknown",
    network: fallback.network,
    displayName: fallback.displayName,
  };
}

export interface InvoiceNetworkInfo {
  network: LightningNetworkIdentity;
  displayName: string;
}

/**
 * Determine the network identity and display name from a BOLT11 invoice string (fallback only).
 *
 * Checks specifically for:
 * 1. Mock Lightning invoices: e.g. "lnbc100mock..." or containing "mock"
 * 2. Regtest invoices: starting with "lnbcrt"
 * 3. Testnet invoices: starting with "lntb"
 * 4. Signet invoices: starting with "lnsbs"
 * 5. Mainnet invoices: starting with "lnbc" (and not a mock invoice)
 */
export function getInvoiceNetworkInfo(invoice?: string | null): InvoiceNetworkInfo {
  if (!invoice) {
    return {
      network: "unknown",
      displayName: "Lightning Network",
    };
  }

  const normalized = invoice.trim().toLowerCase();

  // Mock invoices generated by SatsGrid Mock backend: format `lnbc${sats}mock${hash}`
  // Checked before generic `lnbc` prefix to prevent misidentifying mock invoices as Mainnet.
  if (normalized.includes("mock")) {
    return {
      network: "mock",
      displayName: "Mock Lightning",
    };
  }

  if (normalized.startsWith("lnbcrt")) {
    return {
      network: "regtest",
      displayName: "Bitcoin Regtest (Polar)",
    };
  }

  if (normalized.startsWith("lntb")) {
    return {
      network: "testnet",
      displayName: "Bitcoin Testnet",
    };
  }

  if (normalized.startsWith("lnsbs")) {
    return {
      network: "signet",
      displayName: "Bitcoin Signet",
    };
  }

  if (normalized.startsWith("lnbc")) {
    return {
      network: "mainnet",
      displayName: "Bitcoin Mainnet",
    };
  }

  return {
    network: "unknown",
    displayName: "Lightning Network",
  };
}
